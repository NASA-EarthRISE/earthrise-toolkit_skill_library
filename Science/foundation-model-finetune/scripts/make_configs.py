#!/usr/bin/env python3
"""Generate one TerraTorch config per (backbone run x seed) from a template,
a locked data recipe and an experiment matrix, plus a run script.

Every run shares the SAME data block (roots, bands, norm stats, splits), so
the comparison is apples to apples. Only what the matrix `set`s differs.

Usage
  python make_configs.py --template assets/config_template.yaml \
      --recipe data_recipe.yaml --matrix matrix.yaml --out experiments/
Writes
  experiments/<experiment>/configs/<run>_s<seed>.yaml
  experiments/<experiment>/run_matrix.sh   (fit then test for every config; plain bash,
                                             wrap in your scheduler of choice)
"""
from __future__ import annotations

import argparse
import copy
import os
import stat
from pathlib import Path

import yaml


def set_path(d: dict, dotted: str, value):
    """Set a dotted key. value None deletes the key (e.g. drop backbone_bands for TerraMind)."""
    keys = dotted.split(".")
    for k in keys[:-1]:
        d = d.setdefault(k, {})
    if value is None:
        d.pop(keys[-1], None)
    else:
        d[keys[-1]] = value


def get_path(d: dict, dotted: str, default=None):
    for k in dotted.split("."):
        if not isinstance(d, dict) or k not in d:
            return default
        d = d[k]
    return d


def apply_recipe(cfg: dict, R: dict) -> None:
    sp = R.get("splits", {})
    da = "data.init_args."
    for k, v in {
        "train_data_root": sp.get("train_root"), "val_data_root": sp.get("val_root"),
        "test_data_root": sp.get("test_root"),
        "train_label_data_root": sp.get("train_label_root"), "val_label_data_root": sp.get("val_label_root"),
        "test_label_data_root": sp.get("test_label_root"),
        "img_grep": R.get("image_glob"), "label_grep": R.get("label_glob"),
        "dataset_bands": R["bands"], "output_bands": R["bands"],
        "means": (R.get("norm") or {}).get("means"), "stds": (R.get("norm") or {}).get("stds"),
        "num_classes": R.get("num_classes"),
        "no_data_replace": R.get("no_data_replace", 0), "no_label_replace": R.get("label_nodata", -1),
    }.items():
        if v is not None:
            set_path(cfg, da + k, v)
    ma = "model.init_args."
    set_path(cfg, ma + "model_args.backbone_bands", R["bands"])
    if R.get("num_classes") is not None and R.get("task") == "segmentation":
        set_path(cfg, ma + "model_args.num_classes", R["num_classes"])
        set_path(cfg, ma + "ignore_index", R.get("label_nodata", -1))
        if R.get("class_names"):
            set_path(cfg, ma + "class_names", R["class_names"])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--template", required=True)
    ap.add_argument("--recipe", required=True)
    ap.add_argument("--matrix", required=True)
    ap.add_argument("--out", default="experiments")
    a = ap.parse_args()
    T = yaml.safe_load(open(a.template))
    R = yaml.safe_load(open(a.recipe))
    M = yaml.safe_load(open(a.matrix))
    if not (R.get("norm") or {}).get("means"):
        raise SystemExit("recipe has no norm.means/stds — run check_recipe.py --compute-stats first")
    exp = M["experiment"]
    root = Path(a.out) / exp
    (root / "configs").mkdir(parents=True, exist_ok=True)
    seeds = M.get("seeds", [0, 1, 2])
    if len(seeds) < 3:
        print("WARNING: fewer than 3 seeds — differences between backbones will not be interpretable")
    lines = ["#!/usr/bin/env bash", "# Generated by make_configs.py — fit then test every run.", "set -euo pipefail",
             f'cd "$(dirname "$0")"', ""]
    n = 0
    for run in M["runs"]:
        for seed in seeds:
            cfg = copy.deepcopy(T)
            apply_recipe(cfg, R)
            for k, v in (M.get("set") or {}).items():   # experiment-wide overrides
                set_path(cfg, k, v)
            for k, v in (run.get("set") or {}).items():  # per-run overrides
                set_path(cfg, k, v)
            rid = f"{run['name']}_s{seed}"
            cfg["seed_everything"] = seed
            set_path(cfg, "trainer.max_epochs", M.get("max_epochs", get_path(cfg, "trainer.max_epochs", 50)))
            set_path(cfg, "trainer.default_root_dir", f"runs/{rid}")
            for cb in get_path(cfg, "trainer.callbacks", []) or []:
                if cb.get("class_path", "").endswith("ModelCheckpoint"):
                    cb.setdefault("init_args", {})["dirpath"] = f"checkpoints/{rid}"
            lg = get_path(cfg, "trainer.logger")
            if isinstance(lg, dict):
                lg.setdefault("init_args", {}).update({"save_dir": "runs", "name": rid})
            p = root / "configs" / f"{rid}.yaml"
            p.write_text(f"# run={run['name']} seed={seed} recipe={R.get('name')}\n" + yaml.safe_dump(cfg, sort_keys=False))
            lines += [f"echo '>> {rid}'",
                      f"terratorch fit  -c configs/{rid}.yaml",
                      f"terratorch test -c configs/{rid}.yaml --ckpt_path checkpoints/{rid}/best.ckpt", ""]
            n += 1
    sh = root / "run_matrix.sh"
    sh.write_text("\n".join(lines))
    sh.chmod(sh.stat().st_mode | stat.S_IEXEC)
    print(f"Wrote {n} configs -> {root/'configs'}  and  {sh}")
    print(f"Next: bash {sh}   then   python collect_results.py --runs {root/'runs'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
