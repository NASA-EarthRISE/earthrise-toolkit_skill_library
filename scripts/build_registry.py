#!/usr/bin/env python3
"""Build registry/skills.json and registry/CATALOG.md from every skill.yaml.

Usage:
    python scripts/build_registry.py          # write registry files
    python scripts/build_registry.py --check  # CI: fail if committed registry is out of date
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DOMAINS = ("GIT", "Science", "Solution_Management")
BADGE = {
    "draft": "![draft](https://img.shields.io/badge/skill-draft-lightgrey)",
    "peer-reviewed": "![peer-reviewed](https://img.shields.io/badge/skill-peer--reviewed-blue)",
    "verified": "![verified](https://img.shields.io/badge/skill-verified-brightgreen)",
    "certified": "![certified](https://img.shields.io/badge/skill-program--certified-gold)",
    "deprecated": "![deprecated](https://img.shields.io/badge/skill-deprecated-red)",
    "stale": "![stale](https://img.shields.io/badge/skill-stale-orange)",
}


def load() -> list[dict]:
    out = []
    for d in DOMAINS:
        for y in sorted((ROOT / d).glob("*/skill.yaml")):
            m = yaml.safe_load(y.read_text(encoding="utf-8"))
            due = (m.get("verification") or {}).get("review_due")
            stale = bool(due) and dt.date.fromisoformat(str(due)) < dt.date.today()
            out.append({
                "id": m["id"], "title": m["title"], "domain": m["domain"], "version": m["version"],
                "status": m["status"], "stale": stale, "owner": m["owner"], "summary": m["summary"],
                "tags": m.get("tags", []),
                "inputs": [i["type"] for i in m.get("inputs") or []],
                "outputs": [o["type"] for o in m.get("outputs") or []],
                "composes_with": m.get("composes_with") or {},
                "data_sensitivity": m["data_sensitivity"],
                "path": str(y.parent.relative_to(ROOT)).replace("\\", "/"),
            })
    return out


def chains(skills: list[dict]) -> list[tuple[str, str, str]]:
    """Every (producer, artifact_type, consumer) edge implied by the I/O contracts."""
    consumers = defaultdict(list)
    for s in skills:
        for t in s["inputs"]:
            consumers[t].append(s["id"])
    return sorted({(s["id"], t, c) for s in skills for t in s["outputs"] for c in consumers[t] if c != s["id"]})


def render_catalog(skills: list[dict]) -> str:
    lines = ["# Skill Catalog", "", "_Generated by `scripts/build_registry.py` — do not edit by hand._", ""]
    for d in DOMAINS:
        rows = [s for s in skills if s["domain"] == d]
        lines += [f"## {d.replace('_', ' ')} ({len(rows)})", ""]
        if not rows:
            lines += ["_No skills yet._", ""]
            continue
        lines += ["| Skill | Status | Version | Inputs → Outputs | Owner | Summary |", "|---|---|---|---|---|---|"]
        for s in rows:
            badge = BADGE["stale"] if s["stale"] else BADGE[s["status"]]
            io = f"{', '.join(f'`{i}`' for i in s['inputs']) or '—'} → {', '.join(f'`{o}`' for o in s['outputs'])}"
            lines.append(f"| [`{s['id']}`](../{s['path']}) | {badge} | {s['version']} | {io} | {s['owner']} | {s['summary']} |")
        lines.append("")
    edges = chains(skills)
    lines += ["## Connection map (auto-derived from I/O contracts)", ""]
    if edges:
        lines += ["```mermaid", "flowchart LR"]
        dom = {s["id"]: s["domain"] for s in skills}
        for d in DOMAINS:
            ids = [s["id"] for s in skills if s["domain"] == d]
            if ids:
                lines.append(f"  subgraph {d}")
                lines += [f"    {i}[{i}]" for i in ids]
                lines.append("  end")
        lines += [f"  {a} -- {t} --> {b}" for a, t, b in edges]
        lines += ["```", ""]
        cross = [(a, t, b) for a, t, b in edges if dom[a] != dom[b]]
        lines.append(f"{len(edges)} connections, {len(cross)} cross-team.")
    else:
        lines.append("_No connections yet._")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    skills = load()
    reg = {"skills": skills, "connections": [dict(zip(("from", "artifact", "to"), e)) for e in chains(skills)]}
    j = json.dumps(reg, indent=2, default=str) + "\n"
    md = render_catalog(skills)
    jp, mp = ROOT / "registry" / "skills.json", ROOT / "registry" / "CATALOG.md"
    if a.check:
        stale = [p.name for p, c in ((jp, j), (mp, md)) if not p.exists() or p.read_text() != c]
        if stale:
            print(f"Registry out of date: {stale}. Run: python scripts/build_registry.py")
            return 1
        print("Registry up to date.")
        return 0
    jp.parent.mkdir(exist_ok=True)
    jp.write_text(j)
    mp.write_text(md)
    print(f"Wrote {len(skills)} skills, {len(reg['connections'])} connections -> registry/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
